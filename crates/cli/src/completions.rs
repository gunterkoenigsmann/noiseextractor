//! Shell completion scripts for both programs, printed by
//! `noiseextractor-cli completions SHELL [PROGRAM]`.
//!
//! The command line tool's scripts come from its clap definition, so they
//! never fall behind its options. The GUI (`noiseextractor`) has no options,
//! only files; its scripts complete directories, recordings of the types in
//! [`FILE_TYPES`] and projects ([`PROJECT_FILE_TYPE`]), and are written here
//! for each shell because clap cannot restrict a completion to extensions.
//! The packages install the output (see `packaging/linux/deb.sh`); everyone
//! else can load it from their shell's start-up file, as `docs/completion.md`
//! shows.

use clap::{CommandFactory, ValueEnum};
use clap_complete::Shell;
use noiseextractor_core::audio::FILE_TYPES;
use noiseextractor_core::project_file::PROJECT_FILE_TYPE;
use std::io::Write;

/// The program to complete.
#[derive(Clone, Copy, Debug, PartialEq, Eq, ValueEnum)]
pub enum Program {
    /// The command line tool, `noiseextractor-cli`.
    #[value(name = "noiseextractor-cli")]
    Cli,
    /// The GUI, `noiseextractor`: completes recordings and projects.
    #[value(name = "noiseextractor")]
    Gui,
}

/// The shells completion scripts exist for.
#[derive(Clone, Copy, Debug, PartialEq, Eq, ValueEnum)]
pub enum CompletionShell {
    /// GNU Bash (bash-completion).
    Bash,
    /// Z shell.
    Zsh,
    /// fish.
    Fish,
    /// PowerShell (only for `noiseextractor-cli`).
    Powershell,
    /// Elvish (only for `noiseextractor-cli`).
    Elvish,
}

/// Writes the completion script of `program` for `shell` to `out`.
pub fn write(shell: CompletionShell, program: Program, out: &mut dyn Write) -> anyhow::Result<()> {
    match program {
        Program::Cli => {
            let shell = match shell {
                CompletionShell::Bash => Shell::Bash,
                CompletionShell::Zsh => Shell::Zsh,
                CompletionShell::Fish => Shell::Fish,
                CompletionShell::Powershell => Shell::PowerShell,
                CompletionShell::Elvish => Shell::Elvish,
            };
            let mut cmd = crate::Cli::command();
            clap_complete::generate(shell, &mut cmd, "noiseextractor-cli", out);
            Ok(())
        }
        Program::Gui => {
            let script = match shell {
                CompletionShell::Bash => gui_bash(),
                CompletionShell::Zsh => gui_zsh(),
                CompletionShell::Fish => gui_fish(),
                CompletionShell::Powershell | CompletionShell::Elvish => {
                    anyhow::bail!("completion for noiseextractor exists for bash, zsh and fish")
                }
            };
            out.write_all(script.as_bytes())?;
            Ok(())
        }
    }
}

/// Every extension the GUI opens: projects first, then recordings.
pub fn gui_extensions() -> Vec<&'static str> {
    PROJECT_FILE_TYPE
        .extensions
        .iter()
        .chain(FILE_TYPES.iter().flat_map(|t| t.extensions))
        .copied()
        .collect()
}

/// Bash: bash-completion's `_filedir` matches the extensions in either case
/// and adds directories; without bash-completion `compgen` does the same.
fn gui_bash() -> String {
    let lower = gui_extensions().join("|");
    let both: Vec<String> = gui_extensions()
        .iter()
        .flat_map(|e| [e.to_string(), e.to_uppercase()])
        .collect();
    let both = both.join("|");
    format!(
        r#"# bash completion for noiseextractor: recordings and projects.
# Generated by `noiseextractor-cli completions bash noiseextractor`.
_noiseextractor() {{
    local cur="${{COMP_WORDS[COMP_CWORD]}}"
    if declare -F _filedir > /dev/null; then
        _filedir '@({lower})'
        return
    fi
    # Without bash-completion: extglob is needed for the @(...) pattern.
    local had_extglob=0
    shopt -q extglob && had_extglob=1
    shopt -s extglob
    local IFS=$'\n'
    COMPREPLY=($(compgen -d -- "$cur") $(compgen -f -X '!*.@({both})' -- "$cur"))
    [ "$had_extglob" -eq 1 ] || shopt -u extglob
}}
complete -o filenames -F _noiseextractor noiseextractor
"#
    )
}

/// Zsh: `(#i)` makes the glob ignore case; `_files -g` adds directories.
fn gui_zsh() -> String {
    let exts = gui_extensions().join("|");
    format!(
        r#"#compdef noiseextractor
# zsh completion for noiseextractor: recordings and projects.
# Generated by `noiseextractor-cli completions zsh noiseextractor`.
_arguments '*:recording or project:_files -g "*.(#i)({exts})(-.)"'
"#
    )
}

/// fish: `__fish_complete_suffix` offers files with one of the suffixes,
/// plus directories.
fn gui_fish() -> String {
    let suffixes: Vec<String> = gui_extensions().iter().map(|e| format!(".{e}")).collect();
    format!(
        r#"# fish completion for noiseextractor: recordings and projects.
# Generated by `noiseextractor-cli completions fish noiseextractor`.
complete -c noiseextractor -f -a "(__fish_complete_suffix {})"
"#,
        suffixes.join(" ")
    )
}

#[cfg(test)]
mod tests {
    use super::*;

    /// The script as a string.
    fn script(shell: CompletionShell, program: Program) -> String {
        let mut out = Vec::new();
        write(shell, program, &mut out).unwrap();
        String::from_utf8(out).unwrap()
    }

    #[test]
    fn gui_scripts_name_every_extension() {
        for shell in [CompletionShell::Bash, CompletionShell::Zsh, CompletionShell::Fish] {
            let s = script(shell, Program::Gui);
            for e in gui_extensions() {
                assert!(s.contains(e), "{shell:?} misses {e}");
            }
        }
        assert_eq!(gui_extensions()[0], "nxp");
    }

    #[test]
    fn cli_scripts_know_the_subcommands() {
        let s = script(CompletionShell::Bash, Program::Cli);
        assert!(s.contains("complete -F") && s.contains(" noiseextractor-cli\n"), "{s}");
        for sub in ["process", "denoise", "mark", "discover", "completions"] {
            assert!(s.contains(sub), "{sub}");
        }
        assert!(script(CompletionShell::Zsh, Program::Cli).starts_with("#compdef noiseextractor-cli"));
    }

    #[test]
    fn gui_has_no_powershell_script() {
        let mut out = Vec::new();
        assert!(write(CompletionShell::Powershell, Program::Gui, &mut out).is_err());
    }
}
